#!/usr/bin/env python3
"""
Make SENSEI's interactive pauses opt-in.

The programs call system("pause") at each stage so that a user can follow the
computation step by step. That is useful while learning the method and fatal
for batch reproduction: the published results cannot be regenerated by a
script if every linear solve waits for a keypress.

This script replaces every   system("pause");   with   SENSEI_PAUSE();
and installs the supporting definitions. The behaviour is then controlled at
run time by the SENSEI_INTERACTIVE environment variable:

    SENSEI_INTERACTIVE=1   pause at each stage, as before
    (unset)                run to completion

It also makes the pause portable: system("pause") is a Windows shell builtin,
whereas the replacement uses getchar().

Usage, from 01_source/ :

    python3 tools/make_pauses_optional.py --dry-run     # report only
    python3 tools/make_pauses_optional.py               # apply, writing .bak

Review the diff before committing. Nothing else in the sources is touched.
"""

import argparse
import pathlib
import re
import sys

CALL = 'system("pause");'
REPLACEMENT = "SENSEI_PAUSE();"

HEADER_ANCHOR = "#endif"

HEADER_BLOCK = """
// ------------------------------------------------------------------
//  Interactive stepping
//
//  The programs pause at each stage so a user can follow the run. The
//  pauses are opt-in: set SENSEI_INTERACTIVE=1 in the environment to
//  enable them. Left unset, the programs run unattended, which is what
//  batch reproduction of the published results requires.
// ------------------------------------------------------------------

extern int sensei_interactive;   // -1 not yet resolved, 0 off, 1 on
void sensei_pause(void);
#define SENSEI_PAUSE() sensei_pause()

"""

SOURCE_BLOCK = '''
// ------------------------------------------------------------------
//  Interactive stepping (see functions_SENSEI.h)
// ------------------------------------------------------------------

int sensei_interactive = -1;

void sensei_pause(void)
{
    if (sensei_interactive < 0) {
        const char *e = getenv("SENSEI_INTERACTIVE");
        sensei_interactive = (e && (*e == '1' || *e == 'y' || *e == 'Y' ||
                                    *e == 't' || *e == 'T')) ? 1 : 0;
    }
    if (sensei_interactive) {
        fputs("\\n[SENSEI] Press Enter to continue...", stdout);
        fflush(stdout);
        int c;
        while ((c = getchar()) != '\\n' && c != EOF) { }
    }
}

'''


def find_sources(root: pathlib.Path):
    return sorted(p for p in root.rglob("*.c") if ".git" not in p.parts)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=".", help="source root (default: .)")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    root = pathlib.Path(args.root).resolve()
    core = root / "core" / "functions_SENSEI.c"
    header = root / "include" / "functions_SENSEI.h"

    if not core.exists() or not header.exists():
        # tolerate the flat layout of the development tree
        core = root / "functions_SENSEI.c"
        header = root / "include" / "functions_SENSEI.h"
    if not core.exists() or not header.exists():
        sys.exit(f"cannot find functions_SENSEI.c / .h under {root}")

    total_live = total_commented = 0
    edits = []

    for path in find_sources(root):
        text = path.read_text(encoding="utf-8", errors="surrogateescape")
        live = commented = 0
        out = []
        for line in text.split("\n"):
            if CALL in line:
                if line.lstrip().startswith("//"):
                    commented += line.count(CALL)
                else:
                    live += line.count(CALL)
                    line = line.replace(CALL, REPLACEMENT)
            out.append(line)
        if live:
            edits.append((path, "\n".join(out), live))
        total_live += live
        total_commented += commented
        if live or commented:
            print(f"  {path.relative_to(root)}: {live} active, {commented} already commented out")

    print(f"\n{total_live} active calls to replace "
          f"({total_commented} commented-out occurrences left alone)")

    if args.dry_run:
        print("dry run: nothing written")
        return

    for path, new_text, _ in edits:
        path.with_suffix(path.suffix + ".bak").write_text(
            path.read_text(encoding="utf-8", errors="surrogateescape"),
            encoding="utf-8", errors="surrogateescape")
        path.write_text(new_text, encoding="utf-8", errors="surrogateescape")

    # --- header declaration ---
    h = header.read_text(encoding="utf-8", errors="surrogateescape")
    if "SENSEI_PAUSE" not in h:
        idx = h.rfind(HEADER_ANCHOR)
        if idx == -1:
            sys.exit(f"no trailing {HEADER_ANCHOR} in {header}; add the block by hand")
        header.with_suffix(".h.bak").write_text(h, encoding="utf-8", errors="surrogateescape")
        header.write_text(h[:idx] + HEADER_BLOCK + h[idx:],
                          encoding="utf-8", errors="surrogateescape")
        print(f"declaration added to {header.name}")

    # --- definition ---
    c = core.read_text(encoding="utf-8", errors="surrogateescape")
    if "void sensei_pause(void)" not in c:
        lines = c.split("\n")
        last_include = max((i for i, l in enumerate(lines)
                            if l.strip().startswith("#include")), default=0)
        if "<stdlib.h>" not in c:
            lines.insert(last_include + 1, "#include <stdlib.h>   // getenv")
            last_include += 1
        if "<stdio.h>" not in c:
            lines.insert(last_include + 1, "#include <stdio.h>")
            last_include += 1
        lines.insert(last_include + 1, SOURCE_BLOCK)
        core.write_text("\n".join(lines), encoding="utf-8", errors="surrogateescape")
        print(f"definition added to {core.name}")

    print("\nDone. Originals saved as *.bak. Rebuild and verify against the "
          "reference outputs before committing.")


if __name__ == "__main__":
    main()
